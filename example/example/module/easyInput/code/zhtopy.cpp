ZhToPy::ZhToPy(QObject *parent) : QObject(parent)
{
    file_openstauts = false;
    QString filepath = QCoreApplication::applicationDirPath();
    filepath += "/easyInput/zhtopy.txt";
    QFile file(filepath);

    if (file.open(QFile::ReadOnly | QFile::Text)) {
        QString str = file.readAll();
        listPY = str.split(" ");
        file_openstauts = true;
    }
    file.close();

    init_jplist();
}

QString ZhToPy::zh_to_py(const QString& chinese)
{
    if (file_openstauts == false) {
        return "";
    }
    QStringList list;

    for (int i = 0; i < chinese.length(); ++i) {
        int unicode = QString::number(chinese.at(i).unicode(), 10).toInt();

        if ((unicode >= 0x4E00) && (unicode <= 0x9FA5)) {
            // 这里的listPY就是按照UNICODE每个中文对应的拼音数组
            int index = unicode - 0x4E00;

            if (index < listPY.count()) {
                list.append(listPY.at(index));
            } else {
                qDebug() << "not found:" << chinese.at(i) << listPY.count() <<
                    index;
            }
        } else {
            list.append(chinese.at(i));
        }
    }
    return list.join(" ");
}

QString ZhToPy::zh_to_jp(const QString& chinese)
{
    QString strChineseFirstPY = listJP.join("");

    if (chinese.length() == 0) {
        return chinese;
    }

    QString str;
    int     index = 0;

    for (int i = 0; i < chinese.length(); i++) {
        // 若是字母或数字则直接输出
        ushort vChar = chinese.at(i).unicode();

        if (((vChar >= 'a') && (vChar <= 'z')) ||
            ((vChar >= 'A') && (vChar <= 'Z'))) {
            str.append(chinese.at(i).toUpper());
        }

        if (((vChar >= '0') && (vChar <= '9'))) {
            str.append(chinese.at(i));
        } else {
            index = static_cast<qint32>(vChar - 19968); // 转为qint32

            if ((index >= 0) && (index < strChineseFirstPY.length())) {
                str.append(strChineseFirstPY.at(index));
            }
        }
    }
    return str;
}

QString ZhToPy::get_chinese_pinyin_head_gb2312(QString node)
{
    qpinyin_head.clear();
    QTextCodec *codec2gbk2312 = QTextCodec::codecForName("gb2312");

    // 跟现代的转换方式,在msvc中默认没有启用ICU,因此不可用,官方计划在6.10继承ICU
    // auto sdec=QStringDecoder("gb2312");
    // QString utf16str = sdec(node.toUtf8());
    // auto senc=QStringEncoder("gb2312");
    // QByteArray gb2312Data = senc(node);

    if (codec2gbk2312 != NULL) {
        QByteArray buf = codec2gbk2312->fromUnicode(node); // qt使用Unicode，转化为gb2312

        for (int i = 0; i < buf.size(); i++) {
            if ((quint8)buf.data()[i] < 0x80) {            // gbk第一个字节都大于0x81,小于0x80都是字符字母数字
                qpinyin_head.append(buf.data()[i]);
            } else {
                quint16 nCode = ((buf.data()[i] & 0xff) << 8) +
                                ((buf.data()[i + 1] & 0xff)); // 计算GBK编码
                qpinyin_head.append(convert_gb2312(nCode));
                i++;
            }
        }
    } else {
        qDebug() << "QTextCodec::codecForName(\"gb2312\") error";
    }
    return qpinyin_head;
}

