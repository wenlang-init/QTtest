/* GB2312汉字区(0XB0A1-F7FE)
 *  HiByte(B0-F7) LoByte(A1-FE)
 * GBK编码(8140-FEFE)
 *  汉字区
 *      GB2312汉字区。即GBK/2
 *      GB13000.1扩充汉字区。包含GBK/3（CJK汉字）和GBK/4（CJK汉字和增补汉字）
 *  图形符号区
 *      GB2312非汉字区。即GBK/1 A1A1-A9FE。还有10个小写罗马数字和GB12345增补符号
 *      GB13000.1扩充非汉字区。即GBK/5 A840-A9A0非汉字符号、结构符...
 *  用户自定义区
 * */

// gb2312共6788个汉字,这个函数比较了前55区的汉字
char ZhToPy::convert_gb2312(quint16 n)
{
    // qDebug()<<n;
    if ((n >= 0xb0a1) && (n <= 0xb0c4)) { // b0a1:汉字啊
        return 'a';
    } else if ((n >= 0xb0c5) && (n <= 0xb2c0)) {
        return 'b';
    } else if ((n >= 0xb2c1) && (n <= 0xb4ed)) {
        return 'c';
    } else if ((n >= 0xb4ee) && (n <= 0xb6e9)) {
        return 'd';
    } else if ((n >= 0xb6ea) && (n <= 0xb7a1)) {
        return 'e';
    } else if ((n >= 0xb7a2) && (n <= 0xb8c0)) {
        return 'f';
    } else if ((n >= 0xb8c1) && (n <= 0xb9fd)) {
        return 'g';
    } else if ((n >= 0xb9fe) && (n <= 0xbbf6)) {
        return 'h';
    } else if ((n >= 0xbbf7) && (n <= 0xbfa5)) {
        return 'j';
    } else if ((n >= 0xbfa6) && (n <= 0xc0ab)) {
        return 'k';
    } else if ((n >= 0xc0ac) && (n <= 0xc2e7)) {
        return 'l';
    } else if ((n >= 0xc2e8) && (n <= 0xc4c2)) {
        return 'm';
    } else if ((n >= 0xc4c3) && (n <= 0xc5b5)) {
        return 'n';
    } else if ((n >= 0xc5b6) && (n <= 0xc5bd)) {
        return 'o';
    } else if ((n >= 0xc5be) && (n <= 0xc6d9)) {
        return 'p';
    } else if ((n >= 0xc6da) && (n <= 0xc8ba)) {
        return 'q';
    } else if ((n >= 0xc8bb) && (n <= 0xc8f5)) {
        return 'r';
    } else if ((n >= 0xc8f6) && (n <= 0xcbf0)) {
        return 's';
    } else if ((n >= 0xcbfa) && (n <= 0xcdd9)) {
        return 't';
    } else if ((n >= 0xcdda) && (n <= 0xcef3)) {
        return 'w';
    } else if ((n >= 0xcef4) && (n <= 0xd1b8)) {
        return 'x';
    } else if ((n >= 0xd1b9) && (n <= 0xd4d0)) {
        return 'y';
    } else if ((n >= 0xd4d1) && (n <= 0xd7f9)) { // d7f9:座
        return 'z';
    }
    return '#';
}
